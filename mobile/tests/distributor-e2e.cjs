    console.log("Ingreso ventas");
    const sales=await login('empleado');
    await sales.page.getByRole('tab',{name:'Clientes'}).click();
    await sales.page.getByRole('button',{name:'Nuevo cliente'}).click();
    await sales.page.getByLabel('Nombre comercial').fill('Kiosco Central');
    await sales.page.getByLabel('Dirección de entrega').fill('Calle Principal 123');
    await sales.page.getByRole('button',{name:'Crear cliente'}).click();
    await expect(sales.page.getByText('Kiosco Central',{exact:true})).toBeVisible();
    await sales.page.getByRole('tab',{name:'Pedidos'}).click();
    await sales.page.getByRole('button',{name:'Nuevo pedido'}).click();
    await sales.page.getByRole('button',{name:'Kiosco Central'}).click();
    await sales.page.getByRole('button',{name:/Caja chica estándar · 10 u/}).click();
    await sales.page.getByLabel('Cantidad').click();
    await sales.page.getByLabel('Cantidad').type('2',{delay:100});
    await expect(sales.page.getByLabel('Cantidad')).toHaveValue('2');
    await sales.page.getByRole('button',{name:'Agregar producto'}).click();
    await expect(sales.page.getByText('2 × $12.50')).toBeVisible();
    await sales.page.getByRole('button',{name:/Caja mediana reforzada · 5 u/}).click();
    await sales.page.getByLabel('Cantidad').fill('1');
    await sales.page.getByRole('button',{name:'Agregar producto'}).click();
    await sales.page.getByRole('button',{name:'Crear pedido'}).click();
    await expect(sales.page.getByRole('heading',{name:/Pedido #/})).toBeVisible();
    await expect(sales.page.getByText('Total $30.00')).toBeVisible();
    const [[order]]=await db.query('SELECT id,total FROM pedidos ORDER BY id DESC LIMIT 1');expect(Number(order.total)).toBe(30);
    await sales.context.close();
    console.log("Ingreso depósito");
    const warehouse=await login('encargado');
    await warehouse.page.getByRole('tab',{name:'Pedidos'}).click();
    await warehouse.page.getByRole('button',{name:'Ver detalle y acciones'}).first().click();
    await warehouse.page.getByRole('button',{name:'Aprobar y reservar stock'}).click();
    await warehouse.page.getByRole('button',{name:'Marcar preparado'}).click();
    await warehouse.page.getByRole('button',{name:'repartidor'}).click();
    await warehouse.page.getByRole('button',{name:'Guardar asignación'}).click();
    await warehouse.context.close();
    console.log("Ingreso reparto");
    const driver=await login('repartidor');
    await driver.page.getByRole('tab',{name:'Entregas'}).click();
    await driver.page.getByRole('button',{name:'Ver detalle y acciones'}).first().click();
    await driver.page.getByRole('button',{name:'Confirmar retiro'}).click();
    await driver.page.getByRole('button',{name:'Confirmar entrega'}).click();
    await expect(driver.page.getByText('entregado',{exact:true}).first()).toBeVisible();
    const [[product]]=await db.query("SELECT stock FROM productos WHERE sku='AGUA'");expect(product.stock).toBe(8);
    await driver.page.goBack();
    await driver.page.getByRole('tab',{name:'Inicio'}).click();
    await expect(driver.page.getByRole('tab')).toHaveCount(4);
    await driver.page.screenshot({path:path.resolve(__dirname,'../../docs/carton-repartidor-claro.png'),fullPage:true});
    await driver.page.getByRole('tab',{name:'Mapa'}).click();
    await expect(driver.page.getByText('No hay entregas pendientes asignadas.')).toBeVisible();
    await driver.page.getByRole('tab',{name:'Perfil'}).click();
    await driver.page.getByRole('button',{name:'Oscuro',exact:true}).click();
    await driver.page.screenshot({path:path.resolve(__dirname,'../../docs/carton-perfil-oscuro.png'),fullPage:true});
    await driver.page.getByRole('tab',{name:'Inicio'}).click();
    await driver.page.screenshot({path:path.resolve(__dirname,'../../docs/carton-repartidor-oscuro.png'),fullPage:true});
    await driver.context.close();
    const boss=await login('admin');
    await expect(boss.page.getByRole('tab')).toHaveCount(4);
    await boss.page.screenshot({path:path.resolve(__dirname,'../../docs/carton-dashboard-claro.png'),fullPage:true});
    await boss.page.getByRole('tab',{name:'Inventario'}).click();
    await boss.page.getByRole('button',{name:'Chica',exact:true}).click();
    await expect(boss.page.getByText('Caja chica estándar',{exact:true})).toBeVisible();
    await expect(boss.page.getByText('Caja mediana reforzada',{exact:true})).toHaveCount(0);
    await boss.page.screenshot({path:path.resolve(__dirname,'../../docs/carton-catalogo-claro.png'),fullPage:true});
    await boss.page.getByRole('tab',{name:'Más'}).click();
    await boss.page.getByRole('button',{name:'Perfil y apariencia'}).click();
    await boss.page.getByRole('button',{name:'Oscuro',exact:true}).click();
    await boss.page.getByRole('tab',{name:'Inicio'}).click();
    await boss.page.screenshot({path:path.resolve(__dirname,'../../docs/carton-dashboard-oscuro.png'),fullPage:true});
    await boss.page.getByRole('tab',{name:'Más'}).click();
    await boss.page.getByRole('button',{name:'Valores de cajas',exact:true}).click();
    await boss.page.getByRole('button',{name:'Agregar característica'}).click();
    await boss.page.getByLabel('Característica',{exact:true}).last().fill('Material');
    await boss.page.getByLabel('Opciones separadas por comas').last().fill('Kraft, Blanco');
    await boss.page.getByRole('button',{name:'Guardar valores',exact:true}).click();
    await expect(boss.page.getByText(/Valores guardados/)).toBeVisible();
    await boss.page.screenshot({path:path.resolve(__dirname,'../../docs/valores-cajas.png'),fullPage:true});
    await boss.page.goBack();
    await boss.page.getByRole('tab',{name:'Inventario'}).click();
    await boss.page.getByRole('button',{name:'Nueva caja'}).click();
    await boss.page.getByLabel('Nombre',{exact:true}).fill('Caja circular Kraft');
    await boss.page.getByLabel('SKU único',{exact:true}).fill('CIRC-KRAFT');
    await boss.page.getByLabel('Precio de distribución por unidad').fill('100');
    await boss.page.getByLabel('Alertar poco stock',{exact:true}).fill('12');
    await boss.page.getByLabel('Medidas',{exact:true}).fill('Diámetro 30 cm');
    await boss.page.getByRole('button',{name:'Circular',exact:true}).click();
